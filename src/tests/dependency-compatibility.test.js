const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFile } = require('node:child_process')
const { promisify } = require('node:util')
const JSZip = require('jszip')
const mammoth = require('mammoth')
const exec = promisify(execFile)

test('安全依赖覆盖后Mammoth库与CLI仍能转换合成DOCX', async t => {
  const zip = new JSZip()
  zip.file('[Content_Types].xml', '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>')
  zip.file('_rels/.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>')
  zip.file('word/document.xml', '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>Yan dependency compatibility</w:t></w:r></w:p></w:body></w:document>')
  const buffer = await zip.generateAsync({type:'nodebuffer'})
  assert.match((await mammoth.extractRawText({buffer})).value,/Yan dependency compatibility/)
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'yan-docx-fixture-'))
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}))
  const file = path.join(dir,'fixture.docx')
  fs.writeFileSync(file,buffer)
  const cli = path.join(path.dirname(require.resolve('mammoth/package.json')),'bin','mammoth')
  const result = await exec(process.execPath,[cli,file],{timeout:15000,windowsHide:true})
  assert.match(result.stdout,/<p>Yan dependency compatibility<\/p>/)
})
