test('搜索完整明文优先于被WxLens截断的精确zstd字段，同时回填身份和类型', async () => {
  const text = '长正文🙂'.repeat(900)
  const hex = zstdCompressSync(Buffer.from(text, 'utf8')).toString('hex')
  const hit = { localId: 11, timestamp: 110, sessionId: 'g', type: 0, senderId: '', content: text, contentSource: 'search-index' }
  const direct = { localId: 11, timestamp: 110, type: 1, senderId: 'wxid_person', senderName: '本人', isSelf: true, isSend: 1, content: hex.slice(0, 2000), truncated: true, originalLength: hex.length }
  const merged = await hydrateSearchHits(async () => [direct], [hit], { session_id: 'g', scan_limit: 10 })
  assert.equal(merged[0].content, text)
  assert.equal(merged[0].senderId, 'wxid_person')
  assert.equal(merged[0].type, 1)
  assert.equal(merged[0].contentSource, 'search-index')
  assert.equal(merged[0].contentIntegrity.complete, true)
  assert.equal(merged[0].identityComplete, true)
})
