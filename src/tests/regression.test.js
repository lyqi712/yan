test('长附件正文可按Unicode安全边界分块读取，不丢中文和Emoji', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'yan-text-chunks-')); t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const content = '甲🙂乙中文段落'.repeat(40) + '完整结尾-marker'
  const file = path.join(root, 'long.txt'); fs.writeFileSync(file, content, 'utf8')
  const first = await extractLocalFile(file, [root], { max_chars: 37 })
  assert.equal(first.truncated, true); assert.ok(first.nextOffset > 0); assert.equal(first.text + (await extractLocalFile(file, [root], { max_chars: 1000000, offset_chars: first.nextOffset })).text, content)
  assert.equal(first.text.includes('\uFFFD'), false)
})
test('目录 junction 不能让附件读取逃出白名单', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'yan-boundary-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const allowed = path.join(root, 'allowed'), outside = path.join(root, 'outside')
  fs.mkdirSync(allowed); fs.mkdirSync(outside); fs.writeFileSync(path.join(outside, 'private.txt'), 'synthetic private fixture')
  fs.symlinkSync(outside, path.join(allowed, 'link'), process.platform === 'win32' ? 'junction' : 'dir')
  const target = path.join(allowed, 'link', 'private.txt')
  assert.equal(isWithinAllowedRoots(target, [allowed]), false)
  await assert.rejects(extractLocalFile(target, [allowed]), /白名单|allowlisted/)
  assert.equal(resolveOwnedOutputDir('s', path.join(allowed, 'link', 'new'), allowed), null)
})
test('WxLens 的 zstd 十六进制正文会解成原文，坏载荷不会被当成明文', async () => {
  const text = '做一张精细的SVG图片🙂'
  const hex = zstdCompressSync(Buffer.from(text, 'utf8')).toString('hex')
  const source = [{ localId: 7, timestamp: 70, type: 1, senderId: 'person-a', senderName: '我', isSelf: true, content: hex, contentTruncated: false }]
  const found = await findMessageById(async ({ offset, limit }) => source.slice(offset, offset + limit), { session_id: 'filehelper', local_id: 7, page_size: 10, scan_limit: 10 })
  assert.equal(found.found, true)
  assert.equal(found.message.content, text)
  assert.equal(found.message.contentDecoded, 'zstd')
  assert.equal(found.contentIntegrity.contentUndecoded, false)
  assert.equal(found.contentIntegrity.characters, Array.from(text).length)
  const broken = '28b52ffd' + 'ff'.repeat(16)
  const failed = await findMessageById(async () => [{ localId: 8, timestamp: 80, type: 1, content: broken }], { session_id: 'filehelper', local_id: 8 })
  assert.equal(failed.message.content, broken)
  assert.equal(failed.message.contentUndecoded, true)
  assert.equal(failed.contentIntegrity.contentUndecoded, true)
  const bogus = '28b52ffddeadbeef'
  const empty = await findMessageById(async () => [{ localId: 6, timestamp: 60, type: 1, content: bogus }], { session_id: 'filehelper', local_id: 6 })
  assert.equal(empty.message.content, bogus)
  assert.equal(empty.message.contentDecoded, 'zstd-empty')
})
