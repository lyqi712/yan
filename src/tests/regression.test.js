const rows = Array.from({ length: 12 }, (_, i) => ({ localId: 12 - i, timestamp: 1000 + 12 - i, type: 1, content: `消息 ${12-i}` }))
test('分页中途达到 limit 后，下一页游标不跳过尚未返回的记录', async () => {
  const page = await fetchMessageRange(async ({ limit, offset }) => rows.slice(offset, offset + limit), { limit: 3, page_size: 5 })
  assert.equal(page.pagination.nextOffset, 3)
  const next = await fetchMessageRange(async ({ limit, offset }) => rows.slice(offset, offset + limit), { limit: 3, page_size: 5, offset: page.pagination.nextOffset })
  assert.deepEqual(next.messages.map(m => m.localId), [7, 8, 9])
})
test('重复页必须在有界请求数内停止并标记未完成', async () => {
  let calls = 0
  const page = await fetchMessageRange(async () => { if (++calls > 5) throw new Error('未停止'); return rows.slice(0, 2) }, { limit: 10, page_size: 2 })
  assert.equal(page.pagination.complete, false)
  assert.equal(page.pagination.stopReason, 'no-progress')
})
test('按消息ID精确回查保留长中文和Emoji正文，并返回下一偏移量', async () => {
  const content = '原文🙂中文内容'.repeat(500) + '末尾-marker'
  const source = Array.from({ length: 250 }, (_, index) => ({ localId: 250 - index, timestamp: 1000 - index, content: `synthetic-${index}`, type: 1 }))
  source.push({ localId: 999, timestamp: 1, content, type: 1 })
  const result = await findMessageById(async ({ offset, limit }) => source.slice(offset, offset + limit), { session_id: 'g', local_id: 999, page_size: 50, scan_limit: 500 })
  assert.equal(result.found, true)
  assert.equal(result.message.content, content)
  assert.equal(result.contentIntegrity.characters, Array.from(content).length)
  assert.equal(result.contentIntegrity.utf8Bytes, Buffer.byteLength(content, 'utf8'))
  assert.equal(result.coverage.nextOffset, 251)
})
test('按消息ID精确回查未命中时给出续读范围而非声称全历史不存在', async () => {
  const result = await findMessageById(async ({ offset }) => offset === 0 ? rows.slice(0, 2) : rows.slice(0, 2), { session_id: 'g', local_id: 99, page_size: 2, scan_limit: 6 })
  assert.equal(result.found, false)
  assert.equal(result.partial, true)
  assert.equal(result.coverage.stopReason, 'no-progress')
  assert.equal(result.coverage.nextOffset, 4)
})
